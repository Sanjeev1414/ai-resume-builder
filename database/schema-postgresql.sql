-- =====================================================================
--  AI Resume Builder - database setup (PostgreSQL 13+)
--  Use this for Render, Supabase, Neon or a local PostgreSQL.
-- =====================================================================
--  Step A (local PostgreSQL only - hosted providers create the database
--  and user for you). Run as the postgres superuser:
--
--      CREATE USER resume_app WITH PASSWORD 'ChangeMe_Strong#Pass1';
--      CREATE DATABASE resume_analyzer OWNER resume_app;
--
--  Step B - connect to the resume_analyzer database and run this file:
--      psql -h <host> -U <user> -d resume_analyzer -f database/schema-postgresql.sql
--
--  Then start the backend with:
--      SPRING_PROFILES_ACTIVE=postgres DB_HOST=<host> DB_NAME=resume_analyzer
--      DB_USERNAME=<user> DB_PASSWORD=<password>
--
--  Safe to re-run: everything uses IF NOT EXISTS.
-- =====================================================================

-- Registered users. Passwords are stored only as BCrypt hashes.
CREATE TABLE IF NOT EXISTS users (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    email               VARCHAR(254) NOT NULL,
    password_hash       VARCHAR(255) NOT NULL,
    password_changed_at TIMESTAMP(6) WITH TIME ZONE,            -- login tokens issued before this are rejected
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- One-time password reset links (only a SHA-256 hash of the token is stored).
CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT uk_reset_token_hash UNIQUE (token_hash)
);

-- Resume analyses (AI match score + ATS check). result_json holds the full AI report.
CREATE TABLE IF NOT EXISTS analyses (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    resume_file_name VARCHAR(255) NOT NULL,
    job_description  TEXT NOT NULL,
    match_score      INTEGER NOT NULL,
    result_json      TEXT NOT NULL,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_analyses_user ON analyses (user_id, created_at);

-- AI-generated cover letters (editable by the user).
CREATE TABLE IF NOT EXISTS cover_letters (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    company_name VARCHAR(120),
    job_title    VARCHAR(120),
    tone         VARCHAR(20) NOT NULL,              -- professional | enthusiastic | concise
    subject      VARCHAR(255) NOT NULL,
    content      TEXT NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cover_letters_user ON cover_letters (user_id, created_at);

-- AI interview question sets. result_json holds focus areas + questions.
CREATE TABLE IF NOT EXISTS interview_preps (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    job_title    VARCHAR(120),
    company_name VARCHAR(120),
    result_json  TEXT NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_interview_preps_user ON interview_preps (user_id, created_at);

-- Job tracker entries.
CREATE TABLE IF NOT EXISTS job_applications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    company    VARCHAR(120) NOT NULL,
    role       VARCHAR(120) NOT NULL,
    status     VARCHAR(20) NOT NULL
               CHECK (status IN ('WISHLIST','APPLIED','INTERVIEW','OFFER','REJECTED')),
    location   VARCHAR(120),
    job_url    VARCHAR(500),
    applied_on DATE,
    notes      TEXT,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_job_applications_user ON job_applications (user_id, updated_at);

-- Resume Builder drafts (one per user, stored as the form's JSON).
CREATE TABLE IF NOT EXISTS resume_documents (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    data_json  TEXT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_resume_documents_user UNIQUE (user_id)
);
